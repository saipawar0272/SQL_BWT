--25.	Find all customers located in cities where Serres (SNUM 1002) has customers.

SELECT S.SNUM,S.SNAME,C.CNAME, C.CITY
FROM SALESPERSON S JOIN CUSTOMER C
ON S.SNUM=C.SNUM
HAVING S.SNUM=1002
GROUP BY S.SNUM,S.SNAME,C.CNAME,C.CITY;


