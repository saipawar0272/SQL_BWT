SELECT SYSDATE FROM DUAL;

SELECT SYSDATE, ADD_MONTHS(SYSDATE,1) FROM DUAL;

SELECT SYSDATE, ADD_MONTHS(SYSDATE,2) FROM DUAL;

SELECT EMPLOYEE_ID,FIRST_NAME,SALARY,HIRE_DATE,
 ADD_MONTHS(HIRE_DATE,1) AS HIRE_MONTH
FROM HR.EMPLOYEES;

--18 MONTHS AAGE---

SELECT EMPLOYEE_ID,FIRST_NAME,LAST_NAME,HIRE_DATE,
 ADD_MONTHS(HIRE_DATE,18) FROM HR.EMPLOYEES;
 
 --18 MONTHS PICHE---
 
 SELECT EMPLOYEE_ID,FIRST_NAME,LAST_NAME,HIRE_DATE,
 ADD_MONTHS(HIRE_DATE,-18) FROM HR.EMPLOYEES;
 
 ---CURRENT DATE----
 
 SELECT CURRENT_DATE FROM DUAL; 
 
 SELECT SYSDATE, CURRENT_DATE FROM DUAL;
 
 ----EXTRACT():->EXTRACT ANY PART OF THE DATE
 
 SELECT TO_DATE('31-DEC-1999', 'DD-MON-YYYY') FROM DUAL;
 
 SELECT  EXTRACT (YEAR FROM (TO_DATE('31-DEC-1998', 'DD-MON-YYYY')
 )) FROM DUAL;
 
 SELECT EXTRACT( DAY FROM (TO_DATE('30-DEC-1997', 'DD-MON-YYYY')
 )) FROM DUAL;
 
 SELECT EXTRACT(MONTH FROM TO_DATE('30-DEC-2025', 'DD-MON-YYYY'))
 FROM DUAL;
 
 SELECT EXTRACT(HOUR FROM TO_TIMESTAMP('30-DEC-1995 13:45:54', 
 'DD-MON-YYYY HH24:MI:SS')) AS YEAR_TIME FROM DUAL;
 
 SELECT EXTRACT (HOUR FROM TO_DATE('30-DEC-1997 23:32:14', 
 'DD-MON-YYYY HH24:MI:SS')) FROM DUAL;
 
 
 SELECT EMPLOYEE_ID,FIRST_NAME,HIRE_DATE,
 EXTRACT(MONTH FROM TO_DATE(HIRE_DATE,'DD-MM-YYYY HH24:MI:SS'))
 FROM HR.EMPLOYEES;
 
 SELECT EMPLOYEE_ID,FIRST_NAME,LAST_NAME,HIRE_DATE,
 EXTRACT(MONTH FROM TO_DATE(HIRE_DATE, 'DD-MON-YYYY HH24:MI:SS'))
 FROM HR.EMPLOYEES
 WHERE EXTRACT(MONTH FROM TO_DATE(HIRE_DATE, 'DD-MON-YYYY
 HH24:MI:SS'))=3;
 
 
 ---LAST_DAY():EXTRACT LAST DAY OF THE CURRENT MONTH--
 
 SELECT EMPLOYEE_ID, HIRE_DATE, LAST_DAY(HIRE_DATE) FROM 
 HR.EMPLOYEES;
 
 --EXTRACTING FIRST DAYE OF THE NEST MONTH--
 
 SELECT LAST_DAY(SYSDATE)+1 AS NEXT_DAY_OF_THE_MONTH FROM DUAL;
 
 
 SELECT  EMPLOYEE_ID,HIRE_DATE,NEXT_DAY(HIRE_DATE,'SUNDAY') 
 FROM HR.EMPLOYEES;
 
 SELECT NEXT_DAY(SYSDATE,'SUNDAY') FROM DUAL;
 
 SELECT NEXT_DAY(DATE '2032-01-09', 'MONDAY') FROM DUAL; 
 
 
