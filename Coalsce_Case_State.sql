    WHEN SALARY BETWEEN 7000 AND 9999 THEN 'MEDIUM_SALARY'
      WHEN SALARY BETWEEN 3000 AND 6999 THEN 'LOW_SALARY'
        WHEN SALARY BETWEEN 2500  AND 3000 THEN 'VERY_LOW_SALARY'
