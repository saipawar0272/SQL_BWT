----CASE STATEMENT--------


SELECT FIRST_NAME,EMPLOYEE_ID, SALARY,
CASE
  WHEN SALARY >= 10000 THEN 'HIGH_SALARY'
    WHEN SALARY BETWEEN 5000 AND 9999 THEN 'MEDIUM_SALARY'
      WHEN SALARY < 5000 THEN 'LOW_SALARY'
        ELSE 'NOT_SPECIFIED'
          END AS SALARY_CATEGORY
          FROM HR.EMPLOYEES;
    

SELECT FIRST_NAME,EMPLOYEE_ID, SALARY,
