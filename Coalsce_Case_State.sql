-----USING CASE STATEMENT FOR COMMISSION_PCT

SELECT EMPLOYEE_ID, FIRST_NAME,SALARY ,
CASE 
  WHEN SALARY >=10000 THEN  2.0
    WHEN SALARY BETWEEN 7000 AND 9999 THEN 1.5
      WHEN SALARY BETWEEN 3000 AND 6999 THEN 1.0
        ELSE 0.5
          END AS NEW_COMMISSION
          FROM HR.EMPLOYEES;

-------applying UPDATED COMMISSION PCT ON SALARY

SELECT EMPLOYEE_ID,FIRST_NAME,SALARY,
CASE 
  WHEN SALARY>=10000 THEN 2.0
    WHEN SALARY BETWEEN 6000 AND 9999 THEN 1.5
      WHEN SALARY BETWEEN 3000 AND 5999 THEN 1.0
        ELSE 0.5
          END AS NEW_COMMISSION,
          SALARY * CASE 
          WHEN SALARY >=10000 THEN 2.0
            WHEN SALARY BETWEEN 6000 AND 9999 THEN 1.5
              WHEN SALARY BETWEEN 3000 AND 5999 THEN 1.0
                ELSE 0.5
                  END AS TOTAL_SALARY
                  FROM HR.EMPLOYEES;
                  
