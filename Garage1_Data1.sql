--CUSTOMERS TABLE--

CREATE TABLE GARAGE_CUSTOMERS (
CID NUMBER PRIMARY KEY,
CNAME VARCHAR2(20),
CADD VARCHAR2(40),
C_CONTACT NUMBER,
C_CREDITDAYS NUMBER,
CJ_DATE DATE,
SEX VARCHAR2(10) );

CREATE TABLE GARAGE_VENDORS (
 VID NUMBER PRIMARY KEY,
 VNAME VARCHAR(30),
 VADD VARCHAR2(20),
 VCONTACT NUMBER,
 VCREDITDAYS NUMBER,
 VJ_DATE DATE );
 
 


 CREATE TABLE GARAGE_EMPLOYEE (
 EID NUMBER PRIMARY KEY,
 ENAME VARCHAR2(30),
 EJOB VARCHAR2(20),
 EADD VARCHAR2(30),
 ECONTACT NUMBER,
 ESAL NUMBER,
 EDOJ DATE,
 EDOL DATE);
 
 SELECT * FROM GARAGE_EMPLOYEE;
 
 CREATE TABLE GARAGE_SPAREPART (
 SPID NUMBER PRIMARY KEY,
 SPNAME VARCHAR2(30),
 SPRATE NUMBER,
 SPUNIT VARCHAR2(20) );
 
 
 CREATE TABLE GARAGE_PURCHASE (
 PID NUMBER PRIMARY KEY,
 VID NUMBER,FOREIGN KEY(VID) REFERENCES GARAGE_VENDORS(VID),
 SPID NUMBER, FOREIGN KEY(SPID) REFERENCES GARAGE_SPAREPART(SPID),
 PQTY NUMBER,
 SPRATE NUMBER,
 SPGST VARCHAR2(30),
 SPDATE DATE,
 TRANSCOST NUMBER,
 TOTAL VARCHAR2(20),
 EID NUMBER, FOREIGN KEY(EID) REFERENCES GARAGE_EMPLOYEE );
 
 DROP TABLE GARAGE_DET;
 
 
 CREATE TABLE GARAGE_DET (
 SRID NUMBER PRIMARY KEY,
 CID NUMBER,FOREIGN KEY (CID) REFERENCES GARAGE_CUSTOMERS(CID),
 EID NUMBER, FOREIGN KEY(EID) REFERENCES GARAGE_EMPLOYEE(EID),
 SPID NUMBER, FOREIGN KEY(SPID) REFERENCES GARAGE_SPAREPART(SPID),
 TYP_VEH VARCHAR2(30),
 VEH_NO  VARCHAR2(30),
 TYP_SER VARCHAR2(20),
 SER_DATE DATE,
 QTY NUMBER,
 SP_RATE NUMBER,
 SP_AMT NUMBER,
 SP_GARAGE NUMBER,
 SER_AMT NUMBER,
 COMM NUMBER,
 TOTAL NUMBER );
 
